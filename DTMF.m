clc;
close all;
clear all;

Fs = 8000;
t = 0.5; % 0.5 seconds duration
N = 1:ceil(t*Fs);

disp('Given 4 Low Frequencies');
w = input('Low Frequency 1st (ex- 697): ');
x = input('Low Frequency 2nd (ex- 770): ');
y = input('Low Frequency 3rd (ex- 852): ');
z = input('Low Frequency 4th (ex- 941): ');
R = [w, x, y, z];

disp('Given 3 High Frequencies');
x1 = input('High Frequency 1st (ex- 1209): ');
x2 = input('High Frequency 2nd (ex- 1336): ');
x3 = input('High Frequency 3rd (ex- 1477): ');
C = [x1, x2, x3];

[Ra,Ca] = meshgrid(R,C);
Rb = 2*pi*(Ra(:)/Fs);
Cb = 2*pi*(Ca(:)/Fs);

% ?????? ??????? ????? ?????????? 2 ????? ??? ??? ???
T = (sin(Rb*N) + sin(Cb*N)) / 2;
J = '123456789*0#';

% ????? ????? ???? ?? ??? ?????? ????? ????? ????? ?????? ???
I = input('Enter keys/s [0:9*#]: ','s');
assert(all(ismember(I,J)),'An invalid key was entered');

for k = 1:numel(I)
    X = strfind(J, I(k));
    subplot(4, 3, X);
    
    % ???? ????? ???????? ????? ???? ????? ??? ???????? ???? ??? ???
    plot(T(X, 1:min(200, length(T)))); 
    
    % ??? ???? ???? ?????? ?? ??????? ???? ??????
    xlabel(sprintf('Key: %c', I(k)));
    
    % ????????? Fs-? ?????? ???? ??? ???
    sound(T(X,:), Fs);
    
    pause(0.5);
end
    